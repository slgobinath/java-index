package dev.javaindex.classpath;

import com.google.turbine.binder.bound.TypeBoundClass;
import com.google.turbine.binder.bytecode.BytecodeBoundClass;
import com.google.turbine.binder.sym.ClassSymbol;
import com.google.turbine.binder.sym.TyVarSymbol;
import com.google.turbine.model.TurbineFlag;
import com.google.turbine.model.TurbineTyKind;
import com.google.turbine.type.Type;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

/**
 * Renders a class file as a Java header ("stub") source when no sources jar is available, so that
 * navigation into a dependency still lands on a readable declaration.
 */
final class StubWriter {
  private final Function<String, BytecodeBoundClass> lookup;
  private final StringBuilder out = new StringBuilder();

  private StubWriter(Function<String, BytecodeBoundClass> lookup) {
    this.lookup = lookup;
  }

  static String write(
      String binaryName, BytecodeBoundClass cls, String origin, Function<String, BytecodeBoundClass> lookup) {
    StubWriter w = new StubWriter(lookup);
    w.out.append("// Generated by java-index from ")
        .append(origin == null ? "the JDK" : origin)
        .append(" (no sources available).\n");
    int slash = binaryName.lastIndexOf('/');
    if (slash > 0) {
      w.out.append("package ").append(binaryName.substring(0, slash).replace('/', '.')).append(";\n");
    }
    w.out.append('\n');
    w.type(binaryName, cls, "");
    return w.out.toString();
  }

  private void type(String binaryName, BytecodeBoundClass cls, String indent) {
    int access = cls.access();
    String simple = binaryName.substring(Math.max(binaryName.lastIndexOf('/'), binaryName.lastIndexOf('$')) + 1);
    out.append(indent).append(modifiers(access & ~TurbineFlag.ACC_ABSTRACT & ~TurbineFlag.ACC_INTERFACE, true));
    TurbineTyKind kind = cls.kind();
    if (kind == TurbineTyKind.CLASS && (access & TurbineFlag.ACC_ABSTRACT) != 0) {
      out.append("abstract ");
    }
    out.append(
        switch (kind) {
          case INTERFACE -> "interface ";
          case ENUM -> "enum ";
          case ANNOTATION -> "@interface ";
          default -> "class ";
        });
    out.append(simple).append(typeParams(cls.typeParameterTypes()));
    if (kind == TurbineTyKind.CLASS || kind == TurbineTyKind.RECORD) {
      Type.ClassTy sup = cls.superClassType();
      if (sup != null && !sup.sym().binaryName().equals("java/lang/Object")
          && !sup.sym().binaryName().equals("java/lang/Record")) {
        out.append(" extends ").append(type(sup));
      }
    }
    List<String> ifaces = new ArrayList<>();
    for (Type i : cls.interfaceTypes()) {
      if (kind == TurbineTyKind.ANNOTATION
          && i instanceof Type.ClassTy c
          && c.sym().binaryName().equals("java/lang/annotation/Annotation")) {
        continue;
      }
      ifaces.add(type(i));
    }
    if (!ifaces.isEmpty()) {
      out.append(kind == TurbineTyKind.INTERFACE ? " extends " : " implements ")
          .append(String.join(", ", ifaces));
    }
    out.append(" {\n");
    String inner = indent + "  ";
    if (kind == TurbineTyKind.ENUM) {
      List<String> constants = new ArrayList<>();
      for (TypeBoundClass.FieldInfo f : cls.fields()) {
        if ((f.access() & TurbineFlag.ACC_ENUM) != 0) {
          constants.add(f.name());
        }
      }
      out.append(inner).append(String.join(", ", constants)).append(";\n");
    }
    for (TypeBoundClass.FieldInfo f : cls.fields()) {
      if ((f.access() & (TurbineFlag.ACC_SYNTHETIC | TurbineFlag.ACC_ENUM)) != 0) {
        continue;
      }
      out.append(inner)
          .append(modifiers(f.access(), false))
          .append(type(f.type()))
          .append(' ')
          .append(f.name())
          .append(";\n");
    }
    for (TypeBoundClass.MethodInfo m : cls.methods()) {
      if ((m.access() & (TurbineFlag.ACC_SYNTHETIC | TurbineFlag.ACC_BRIDGE)) != 0
          || m.name().equals("<clinit>")) {
        continue;
      }
      int mAccess = m.access();
      if (kind == TurbineTyKind.INTERFACE || kind == TurbineTyKind.ANNOTATION) {
        mAccess &= ~(TurbineFlag.ACC_PUBLIC | TurbineFlag.ACC_ABSTRACT);
      }
      out.append(inner).append(modifiers(mAccess, false));
      String tps = typeParams(m.tyParams());
      if (!tps.isEmpty()) {
        out.append(tps).append(' ');
      }
      boolean ctor = m.name().equals("<init>");
      if (ctor) {
        out.append(simple);
      } else {
        out.append(type(m.returnType())).append(' ').append(m.name());
      }
      out.append('(');
      List<String> params = new ArrayList<>();
      int n = 0;
      for (TypeBoundClass.ParamInfo p : m.parameters()) {
        if (p.synthetic()) {
          continue;
        }
        String name = p.name() == null || p.name().isEmpty() ? "arg" + n : p.name();
        params.add(type(p.type()) + " " + name);
        n++;
      }
      if ((m.access() & TurbineFlag.ACC_VARARGS) != 0 && !params.isEmpty()) {
        String last = params.removeLast();
        int sp = last.lastIndexOf(' ');
        String ty = last.substring(0, sp);
        if (ty.endsWith("[]")) {
          ty = ty.substring(0, ty.length() - 2) + "...";
        }
        params.add(ty + last.substring(sp));
      }
      out.append(String.join(", ", params)).append(')');
      if (!m.exceptions().isEmpty()) {
        List<String> ex = new ArrayList<>();
        m.exceptions().forEach(e -> ex.add(type(e)));
        out.append(" throws ").append(String.join(", ", ex));
      }
      out.append(";\n");
    }
    for (Map.Entry<String, ClassSymbol> child : cls.children().entrySet()) {
      BytecodeBoundClass c = lookup.apply(child.getValue().binaryName());
      if (c != null) {
        out.append('\n');
        type(child.getValue().binaryName(), c, inner);
      }
    }
    out.append(indent).append("}\n");
  }

  private static String modifiers(int access, boolean isClass) {
    StringBuilder sb = new StringBuilder();
    if ((access & TurbineFlag.ACC_PUBLIC) != 0) sb.append("public ");
    if ((access & TurbineFlag.ACC_PROTECTED) != 0) sb.append("protected ");
    if ((access & TurbineFlag.ACC_PRIVATE) != 0) sb.append("private ");
    if ((access & TurbineFlag.ACC_STATIC) != 0) sb.append("static ");
    if (!isClass && (access & TurbineFlag.ACC_ABSTRACT) != 0) sb.append("abstract ");
    if ((access & TurbineFlag.ACC_FINAL) != 0 && (access & TurbineFlag.ACC_ENUM) == 0) {
      sb.append("final ");
    }
    if (!isClass && (access & TurbineFlag.ACC_NATIVE) != 0) sb.append("native ");
    return sb.toString();
  }

  private String typeParams(Map<TyVarSymbol, TypeBoundClass.TyVarInfo> params) {
    if (params.isEmpty()) {
      return "";
    }
    List<String> out = new ArrayList<>();
    for (Map.Entry<TyVarSymbol, TypeBoundClass.TyVarInfo> e : params.entrySet()) {
      List<String> bounds = new ArrayList<>();
      for (Type b : e.getValue().upperBound().bounds()) {
        String s = type(b);
        if (!s.equals("java.lang.Object")) {
          bounds.add(s);
        }
      }
      out.add(e.getKey().name() + (bounds.isEmpty() ? "" : " extends " + String.join(" & ", bounds)));
    }
    return "<" + String.join(", ", out) + ">";
  }

  private static String type(Type t) {
    return switch (t) {
      case Type.ClassTy c -> {
        StringBuilder sb = new StringBuilder();
        List<Type.ClassTy.SimpleClassTy> parts = c.classes();
        for (int i = 0; i < parts.size(); i++) {
          Type.ClassTy.SimpleClassTy p = parts.get(i);
          if (i == 0) {
            sb.append(p.sym().binaryName().replace('/', '.').replace('$', '.'));
          } else {
            sb.append('.').append(p.sym().simpleName());
          }
          if (!p.targs().isEmpty()) {
            List<String> args = new ArrayList<>();
            p.targs().forEach(a -> args.add(type(a)));
            sb.append('<').append(String.join(", ", args)).append('>');
          }
        }
        yield sb.toString();
      }
      case Type.TyVar v -> v.sym().name();
      case Type.ArrayTy a -> type(a.elementType()) + "[]";
      case Type.PrimTy p -> p.primkind().toString();
      case Type.WildUpperBoundedTy w -> "? extends " + type(w.bound());
      case Type.WildLowerBoundedTy w -> "? super " + type(w.bound());
      case Type.WildTy w -> "?";
      default -> t.tyKind() == Type.TyKind.VOID_TY ? "void" : "java.lang.Object";
    };
  }
}
